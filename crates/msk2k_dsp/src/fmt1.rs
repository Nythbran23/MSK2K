/// Format-1 interleaver: matches Python `interleave_format1()`
pub fn interleave_format1(
    sync_bits: &[i32],
    addr_bits: &[i32],
    poly1_bits: &[i32],
    poly2_bits: &[i32],
) -> Vec<i32> {
    if sync_bits.len() != 43 || addr_bits.len() != 49 {
        panic!(
            "Invalid sync/addr lengths: sync={} addr={}",
            sync_bits.len(),
            addr_bits.len()
        );
    }
    if poly1_bits.len() != 83 || poly2_bits.len() != 83 {
        panic!(
            "Invalid polynomial lengths: poly1={} poly2={}",
            poly1_bits.len(),
            poly2_bits.len()
        );
    }

    let mut packet = vec![0i32; 258];

    for (pos, (tc, one_based_idx)) in FORMAT1_TABLE.iter().enumerate() {
        let idx = (*one_based_idx as usize) - 1;
        packet[pos] = match *tc {
            b'S' => sync_bits[idx],
            b'A' => addr_bits[idx],
            b'1' => poly1_bits[idx],
            b'2' => poly2_bits[idx],
            _ => panic!("Unknown FORMAT1_TABLE type code: {}", *tc as char),
        };
    }

    packet
}

pub fn deinterleave_format1(packet: &[i32]) -> (Vec<i32>, Vec<i32>, Vec<i32>, Vec<i32>) {
    if packet.len() != 258 {
        panic!(
            "deinterleave_format1 requires 258 bits, got {}",
            packet.len()
        );
    }

    let mut sync_bits = vec![0i32; 43];
    let mut addr_bits = vec![0i32; 49];
    let mut poly1 = vec![0i32; 83];
    let mut poly2 = vec![0i32; 83];

    for (pos, (tc, one_based_idx)) in FORMAT1_TABLE.iter().enumerate() {
        let idx = (*one_based_idx as usize) - 1;
        match *tc {
            b'S' => sync_bits[idx] = packet[pos],
            b'A' => addr_bits[idx] = packet[pos],
            b'1' => poly1[idx] = packet[pos],
            b'2' => poly2[idx] = packet[pos],
            _ => panic!("Unknown FORMAT1_TABLE type code: {}", *tc as char),
        }
    }

    (sync_bits, addr_bits, poly1, poly2)
}

